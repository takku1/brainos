"""Drift control: the requirement register, documents and code must agree.

    py tools/check_traceability.py           # check; exit 1 on any drift
    py tools/check_traceability.py --write   # regenerate the derived cells/columns/sections

Source of truth: docs/current/traceability.json (see Doc 31 section 31.12).
Derived (regenerated by --write, verified otherwise):
  * I/V cells of every register row in Doc 31
  * the Status column of docs/current/README.md
  * Doc 21's current-state map between the traceability markers
Checked:
  * every cited code symbol and test exists (parsed with ast, never imported)
  * every src/brainos module and every test class is claimed by a requirement
  * every document's `Status:` header is consistent with the rows it owns
  * docs/STATUS.md carries the required sections, register-derived counts,
    a live workstream and a dated update (workstream exit check, Doc 08 rule 4)
"""
from pathlib import Path
import ast
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "current"
MAP = DOCS / "traceability.json"
REGISTER = DOCS / "31-architectural-audit.md"
README = DOCS / "README.md"
DOC21 = DOCS / "21-reference-implementation.md"
STATUS = ROOT / "docs" / "STATUS.md"
BEGIN, END = "<!-- traceability:begin -->", "<!-- traceability:end -->"

I_TOKEN = {"implemented": "I✓", "partial": "I∼", "specified": "I✗", "documentary": "I—"}
DOC_STATUSES = ("implemented", "partial", "specified", "research", "documentary")
ROW_RE = re.compile(r"^(R-[A-Za-z0-9\-]+) \|")
CELL_RE = re.compile(r"I[✓~✗∼—-] V[✓~✗∼—-]")
STATUS_LINE_RE = re.compile(r"^Status: (\w+)\b")


def symbols(path):
    """{'Name', 'Class.method'} defined at module level in a Python file."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
            if isinstance(node, ast.ClassDef):
                names.update(f"{node.name}.{m.name}" for m in node.body if isinstance(m, ast.FunctionDef))
    return names


def test_classes(path):
    """Classes in a test file that define at least one test_ method."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {n.name for n in tree.body if isinstance(n, ast.ClassDef)
            and any(isinstance(m, ast.FunctionDef) and m.name.startswith("test_") for m in n.body)}


def resolve(ref, errors, where):
    if "::" not in ref:
        errors.append(f"{where}: reference {ref!r} must be path::symbol")
        return None
    path, name = ref.split("::", 1)
    file = ROOT / path
    if not file.exists():
        errors.append(f"{where}: {path} does not exist")
        return None
    if name not in symbols(file):
        errors.append(f"{where}: {path} defines no {name!r}")
        return None
    return path, name


def register_rows(text):
    rows = {}
    for number, line in enumerate(text.splitlines()):
        match = ROW_RE.match(line)
        if match:
            rows[match.group(1)] = number
    return rows


def expected_cells(entry):
    status = entry.get("status", "specified")
    if not entry.get("tests"):
        v = "V✗"
    elif entry.get("verified") == "full":
        v = "V✓"
    else:
        v = "V∼"
    return f"{I_TOKEN[status]} {v}"


def doc_number(requirement):
    return requirement.split("-")[1]


def derived_doc_status(statuses):
    """Allowed header values for a document given the statuses of the rows it owns."""
    built = {"implemented", "partial"} & set(statuses)
    if not statuses:
        return {"documentary", "research", "specified"}
    if built:
        return {"implemented"} if set(statuses) <= {"implemented", "documentary"} else {"partial"}
    if set(statuses) <= {"documentary"}:
        return {"documentary"}
    return {"specified", "research"}


def generate_doc21_map(reqs):
    modules = sorted(p.name for p in (ROOT / "src" / "brainos").glob("*.py") if p.name != "__init__.py")
    lines = [BEGIN, "",
             "Generated by `tools/check_traceability.py --write` from `docs/current/traceability.json`;",
             "do not edit by hand. Status per requirement: implemented (I✓), partial (I∼).", "",
             "| Module | Requirements (implemented) | Requirements (partial) |", "|---|---|---|"]
    for module in modules:
        full, part = [], []
        for rid, entry in sorted(reqs.items()):
            if any(ref.split("::")[0] == f"src/brainos/{module}" for ref in entry.get("code", [])):
                (full if entry["status"] == "implemented" else part).append(rid)
        lines.append(f"| {module} | {', '.join(full) or '—'} | {', '.join(part) or '—'} |")
    counts = {}
    for entry in reqs.values():
        counts[entry["status"]] = counts.get(entry["status"], 0) + 1
    lines += ["", "Register totals: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".", "", END]
    return "\n".join(lines)


def check_status(reqs, errors):
    """Workstream exit check: STATUS.md must reflect the register, not older text."""
    if not STATUS.exists():
        errors.append("docs/STATUS.md is missing")
        return
    text = STATUS.read_text(encoding="utf-8")
    lower = text.lower()
    for section in ("current phase", "active focus", "architecture summary", "key decisions",
                    "deprecated", "last updated"):
        if section not in lower:
            errors.append(f"STATUS.md lacks required section: {section}")
    counts = {}
    for entry in reqs.values():
        counts[entry.get("status", "specified")] = counts.get(entry.get("status", "specified"), 0) + 1
    match = re.search(r"register:\s*(\d+)\s+requirements\s*\(implemented\s+(\d+),\s*"
                      r"partial\s+(\d+),\s*specified\s+(\d+),\s*documentary\s+(\d+)\)", lower)
    if match is None:
        errors.append("STATUS.md lacks a derived register line "
                      "'register: N requirements (implemented I, partial P, specified S, documentary D)'")
    else:
        total, impl, part, spec, doc = (int(match.group(i)) for i in range(1, 6))
        want = (len(reqs), counts.get("implemented", 0), counts.get("partial", 0),
                counts.get("specified", 0), counts.get("documentary", 0))
        if (total, impl, part, spec, doc) != want:
            errors.append(f"STATUS.md register line says {(total, impl, part, spec, doc)}, "
                          f"register has {want}")
    roadmap = (DOCS / "08-development-roadmap.md").read_text(encoding="utf-8")
    for token in sorted(set(re.findall(r"W[0-7]", text))):
        if token not in roadmap:
            errors.append(f"STATUS.md names {token}, which no Doc 08 workstream defines")
    if not re.search(r"## Last updated\s+202\d-\d{2}-\d{2}", text):
        errors.append("STATUS.md needs a dated entry directly under 'Last updated'")


def main():
    write = "--write" in sys.argv[1:]
    errors = []
    data = json.loads(MAP.read_text(encoding="utf-8"))
    mapping = data["requirements"]
    register = REGISTER.read_text(encoding="utf-8")
    rows = register_rows(register)

    for rid in mapping:
        if rid not in rows:
            errors.append(f"map entry {rid} has no register row")
    reqs = {rid: dict(mapping.get(rid, {"status": "specified"})) for rid in rows}
    check_status(reqs, errors)
    for rid, entry in reqs.items():
        entry.setdefault("status", "specified")
        if entry["status"] not in I_TOKEN:
            errors.append(f"{rid}: unknown status {entry['status']!r}")
            continue
        for ref in entry.get("code", []):
            resolve(ref, errors, rid)
        for ref in entry.get("tests", []):
            resolved = resolve(ref, errors, rid)
            if resolved and not resolved[0].startswith("tests/"):
                errors.append(f"{rid}: test reference {ref!r} is not under tests/")
        if entry["status"] in ("implemented", "partial") and not entry.get("code"):
            errors.append(f"{rid}: {entry['status']} without code references")
        if entry["status"] == "implemented" and not entry.get("tests"):
            errors.append(f"{rid}: implemented without tests")
        if entry["status"] in ("specified", "documentary") and entry.get("code"):
            errors.append(f"{rid}: {entry['status']} must not cite implementing code")

    # Register cells.
    lines = register.splitlines()
    for rid, number in rows.items():
        want = expected_cells(reqs[rid])
        have = CELL_RE.search(lines[number])
        if not have:
            errors.append(f"{rid}: register row has no I/V cells")
        elif have.group(0) != want:
            if write:
                lines[number] = lines[number][:have.start()] + want + lines[number][have.end():]
            else:
                errors.append(f"{rid}: register says {have.group(0)}, map says {want}")
    if write:
        REGISTER.write_text("\n".join(lines) + ("\n" if register.endswith("\n") else ""), encoding="utf-8")

    # Orphans.
    claimed_code = {ref.split("::")[0] for e in reqs.values() for ref in e.get("code", [])}
    claimed_tests = {(ref.split("::")[0], ref.split("::")[1].split(".")[0]) for e in reqs.values()
                     for ref in e.get("tests", [])}
    for module in sorted((ROOT / "src" / "brainos").glob("*.py")):
        rel = module.relative_to(ROOT).as_posix()
        if module.name != "__init__.py" and rel not in claimed_code:
            errors.append(f"orphan module: {rel} is claimed by no requirement")
    for test_file in sorted((ROOT / "tests").glob("test_*.py")):
        rel = test_file.relative_to(ROOT).as_posix()
        for cls in sorted(test_classes(test_file)):
            if (rel, cls) not in claimed_tests:
                errors.append(f"orphan test class: {rel}::{cls} is claimed by no requirement")

    # Document status headers and README column.
    owned = {}
    for rid, entry in reqs.items():
        owned.setdefault(doc_number(rid), []).append(entry["status"])
    headers = {}
    for doc in sorted(DOCS.glob("[0-9][0-9]-*.md")):
        number = doc.name[:2]
        text = doc.read_text(encoding="utf-8").splitlines()
        status = next((STATUS_LINE_RE.match(l).group(1) for l in text[:6] if STATUS_LINE_RE.match(l)), None)
        if status is None:
            errors.append(f"{doc.name}: missing 'Status:' header in the first lines")
            continue
        if status not in DOC_STATUSES:
            errors.append(f"{doc.name}: unknown status {status!r}")
        allowed = derived_doc_status(owned.get(number, []))
        if status not in allowed:
            errors.append(f"{doc.name}: header says {status}, its rows allow {sorted(allowed)}")
        headers[number] = status
    readme = README.read_text(encoding="utf-8").splitlines()
    out = []
    for line in readme:
        match = re.match(r"^\| (\d\d) \| (\[[^\]]+\]\([^)]+\)) \| (.*?) \|( [a-z]+ \|)?$", line)
        if match and match.group(1) in headers:
            want = f"| {match.group(1)} | {match.group(2)} | {match.group(3)} | {headers[match.group(1)]} |"
            if line != want:
                if write:
                    line = want
                else:
                    errors.append(f"README row {match.group(1)} status column out of date")
        elif line.startswith("| # | Document | Contents |"):
            want_header = "| # | Document | Contents | Status |"
            if line != want_header:
                if write:
                    line = want_header
                else:
                    errors.append("README document table lacks the Status column")
        elif line.startswith("|---|----------|----------|"):
            if line != "|---|----------|----------|---|":
                if write:
                    line = "|---|----------|----------|---|"
                else:
                    errors.append("README document table separator lacks the Status column")
        out.append(line)
    if write:
        README.write_text("\n".join(out) + "\n", encoding="utf-8")

    # Doc 21 generated map.
    body = DOC21.read_text(encoding="utf-8")
    generated = generate_doc21_map(reqs)
    if BEGIN not in body or END not in body:
        errors.append("Doc 21 lacks the traceability markers")
    else:
        current = body[body.index(BEGIN):body.index(END) + len(END)]
        if current != generated:
            if write:
                DOC21.write_text(body.replace(current, generated), encoding="utf-8")
            else:
                errors.append("Doc 21 current-state map is out of date (run --write)")

    counts = {}
    for entry in reqs.values():
        counts[entry["status"]] = counts.get(entry["status"], 0) + 1
    if write:
        print("regenerated derived cells; rerun without --write to check")
    for e in errors:
        print("DRIFT:", e)
    print(f"{len(rows)} requirements: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items()))
          + f"; {len(errors)} drift errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
